        class SPURSStructureAdapter(nn.Module):
            """Fix 7: SPURS-style cross-modal structure adapter fusing `ProteinMPNNStructureEncoder`
            features `h_struct` (`[B, L, 128]`) with `ESM-2` representations `h_esm` (`[B, L, D_esm]`).
            Uses a bottleneck projection + gated residual fusion masked by `residue_valid_mask`.
            """

            def __init__(
                self,
                esm_hidden_dim: int,
                struct_dim: int = 128,
                adapter_bottleneck_dim: int = 128,
                dropout: float = 0.1,
            ) -> None:
                super().__init__()
                self.struct_proj = nn.Sequential(
                    nn.LayerNorm(struct_dim),
                    nn.Linear(struct_dim, adapter_bottleneck_dim),
                    nn.GELU(),
                    nn.Dropout(dropout),
                    nn.Linear(adapter_bottleneck_dim, esm_hidden_dim),
                    nn.LayerNorm(esm_hidden_dim),
                )
                self.gate_proj = nn.Linear(esm_hidden_dim * 2, esm_hidden_dim)
                nn.init.constant_(self.gate_proj.bias, -1.0)

            def forward(
                self,
                h_esm: torch.Tensor,
                h_struct: torch.Tensor,
                residue_valid_mask: torch.Tensor,
            ) -> torch.Tensor:
                s_proj = self.struct_proj(h_struct)
                gate = torch.sigmoid(self.gate_proj(torch.cat([h_esm, s_proj], dim=-1)))
                vmask = residue_valid_mask.float().unsqueeze(-1)
                return h_esm + (gate * vmask) * s_proj

        class ESM2WildTypeStabilityModel(nn.Module):
            """Pretrained ESM-2 stability model with optional `ProteinMPNNStructureEncoder` + `SPURSStructureAdapter`.
            - Takes wild-type sequence (`wt_seq`) in one forward pass per protein.
            - Outputs `[B, L, 20]` predicted ΔΔG mapped 1-to-1 to `ACDEFGHIKLMNPQRSTVWY`, zero-anchored at `wt_aa`.
            """

            def __init__(
                self,
                esm_masked_lm: nn.Module,
                aa_token_ids: List[int],
                hidden_dim: int,
                finetune_mode: str = "lora",
                lora_rank: int = 8,
                lora_alpha: float = 16.0,
                lora_dropout: float = 0.05,
                llr_sign_multiplier: float = 1.0,
                use_spurs_adapter: bool = False,
                mpnn_encoder: Optional[ProteinMPNNStructureEncoder] = None,
                freeze_mpnn_encoder: bool = True,
                include_handcrafted_3d: bool = False,
                handcrafted_3d_dim: int = 29,
            ) -> None:
                super().__init__()
                self.esm = esm_masked_lm
                self.finetune_mode = finetune_mode
                self.use_spurs_adapter = bool(use_spurs_adapter)
                self.include_handcrafted_3d = bool(include_handcrafted_3d)
                self.register_buffer("aa_token_ids", torch.tensor(aa_token_ids, dtype=torch.long))
                self.llr_sign_multiplier = float(llr_sign_multiplier)

                for p in self.esm.parameters():
                    p.requires_grad = False

                self.n_lora_modules = 0
                self.lora_module_names: List[str] = []
                if finetune_mode == "lora":
                    self.n_lora_modules, self.lora_module_names = inject_lora_into_esm_backbone(
                        self.esm, rank=lora_rank, alpha=lora_alpha, dropout=lora_dropout
                    )
                elif finetune_mode == "full":
                    for p in self.esm.parameters():
                        p.requires_grad = True
                elif finetune_mode != "frozen":
                    raise ValueError(f"Unknown finetune_mode: {finetune_mode}")

                if self.use_spurs_adapter:
                    self.mpnn_encoder = (
                        mpnn_encoder
                        if mpnn_encoder is not None
                        else ProteinMPNNStructureEncoder(hidden_dim=128)
                    )
                    if freeze_mpnn_encoder:
                        for p in self.mpnn_encoder.parameters():
                            p.requires_grad = False
                    self.spurs_adapter = SPURSStructureAdapter(
                        esm_hidden_dim=hidden_dim, struct_dim=128, adapter_bottleneck_dim=128
                    )
                else:
                    self.mpnn_encoder = None
                    self.spurs_adapter = None

                in_dim = hidden_dim + (handcrafted_3d_dim if self.include_handcrafted_3d else 0)
                self.head = nn.Sequential(
                    nn.LayerNorm(in_dim),
                    nn.Linear(in_dim, 256),
                    nn.GELU(),
                    nn.Dropout(0.10),
                    nn.Linear(256, 20),
                )
                self.alpha_llr = nn.Parameter(torch.tensor(0.25, dtype=torch.float32))

            def forward(
                self,
                input_ids: torch.Tensor,
                attention_mask: torch.Tensor,
                wt_seq_indices: torch.Tensor,
                lengths: torch.Tensor,
                backbone_coords: Optional[torch.Tensor] = None,
                residue_valid_mask: Optional[torch.Tensor] = None,
                struct_env_feats: Optional[torch.Tensor] = None,
            ) -> torch.Tensor:
                if self.finetune_mode == "frozen":
                    self.esm.eval()
                    with torch.no_grad():
                        outputs = self.esm(
                            input_ids=input_ids,
                            attention_mask=attention_mask,
                            output_hidden_states=True,
                        )
                else:
                    outputs = self.esm(
                        input_ids=input_ids,
                        attention_mask=attention_mask,
                        output_hidden_states=True,
                    )

                Lmax = wt_seq_indices.shape[1]
                hidden = outputs.hidden_states[-1][:, 1 : Lmax + 1, :]
                logits = outputs.logits[:, 1 : Lmax + 1, :]

                logits_20 = torch.index_select(logits, dim=-1, index=self.aa_token_ids)
                log_probs_20 = F.log_softmax(logits_20, dim=-1)

                safe_wt_idx = torch.clamp(wt_seq_indices, min=0, max=19).unsqueeze(-1)
                wt_log_prob = torch.gather(log_probs_20, dim=-1, index=safe_wt_idx)
                llr_20 = (log_probs_20 - wt_log_prob) * self.llr_sign_multiplier

                if (
                    self.use_spurs_adapter
                    and self.mpnn_encoder is not None
                    and self.spurs_adapter is not None
                    and backbone_coords is not None
                    and residue_valid_mask is not None
                ):
                    h_struct = self.mpnn_encoder(backbone_coords, residue_valid_mask)
                    hidden = self.spurs_adapter(hidden, h_struct, residue_valid_mask)

                if self.include_handcrafted_3d and struct_env_feats is not None:
                    head_in = torch.cat([hidden, struct_env_feats], dim=-1)
                else:
                    head_in = hidden

                raw_delta = self.head(head_in)
                wt_delta = torch.gather(raw_delta, dim=-1, index=safe_wt_idx)
                centered_delta = raw_delta - wt_delta

                pred_ddg = self.alpha_llr * llr_20 + centered_delta
                return pred_ddg

