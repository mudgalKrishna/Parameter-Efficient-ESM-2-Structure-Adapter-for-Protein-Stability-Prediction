    def evaluate_split_with_bootstrap_ci(
        y_true_grid: np.ndarray,
        y_pred_grid: np.ndarray,
        label_mask_grid: np.ndarray,
        protein_ids: np.ndarray,
        n_boot: int = 2000,
        seed: int = 42,
    ) -> Tuple[Dict[str, Any], pd.DataFrame]:
        """Fixes 17, 18, 30, 31: Compute per-protein and pooled metrics with deterministic
        protein-level bootstrap 95% CIs. Transparently skips proteins with undefined/constant
        correlations instead of replacing them with 0.0.
        """
        if y_true_grid.shape != y_pred_grid.shape or y_true_grid.shape != label_mask_grid.shape:
            raise ValueError(
                f"Shape mismatch in evaluate_split_with_bootstrap_ci: y_true={y_true_grid.shape}, "
                f"y_pred={y_pred_grid.shape}, mask={label_mask_grid.shape}"
            )

        per_prot_rows: List[Dict[str, Any]] = []
        excluded_proteins: List[str] = []
        all_yt: List[np.ndarray] = []
        all_yp: List[np.ndarray] = []

        for i, pid in enumerate(protein_ids):
            pid_str = str(pid)
            m = label_mask_grid[i]
            n_v = int(np.sum(m))
            if n_v < 3:
                excluded_proteins.append(f"{pid_str}(n_variants={n_v}<3)")
                continue
            yt = y_true_grid[i][m].astype(np.float64)
            yp = y_pred_grid[i][m].astype(np.float64)
            if not (np.all(np.isfinite(yt)) and np.all(np.isfinite(yp))):
                excluded_proteins.append(f"{pid_str}(non_finite_values)")
                continue
            all_yt.append(yt)
            all_yp.append(yp)

            if np.std(yt) <= 1e-9 or np.std(yp) <= 1e-9:
                excluded_proteins.append(f"{pid_str}(constant_predictions_or_targets)")
                continue

            sp_rho = float(scipy_stats.spearmanr(yt, yp).correlation)
            pe_r = float(np.corrcoef(yt, yp)[0, 1])
            if not (np.isfinite(sp_rho) and np.isfinite(pe_r)):
                excluded_proteins.append(f"{pid_str}(nan_correlation)")
                continue

            mae = float(np.mean(np.abs(yt - yp)))
            rmse = float(np.sqrt(np.mean((yt - yp) ** 2)))
            per_prot_rows.append(
                {
                    "protein_id": pid_str,
                    "n_variants": n_v,
                    "spearman_rho": sp_rho,
                    "pearson_r": pe_r,
                    "mae": mae,
                    "rmse": rmse,
                }
            )

        if not per_prot_rows:
            raise RuntimeError(
                f"All {len(protein_ids)} proteins were excluded due to invalid/constant predictions: {excluded_proteins[:5]}"
            )

        prot_df = pd.DataFrame(per_prot_rows)
        rhos = prot_df["spearman_rho"].to_numpy(dtype=np.float64)
        rs = prot_df["pearson_r"].to_numpy(dtype=np.float64)
        maes = prot_df["mae"].to_numpy(dtype=np.float64)
        rmses = prot_df["rmse"].to_numpy(dtype=np.float64)

        yt_pool = np.concatenate(all_yt) if all_yt else np.zeros(1)
        yp_pool = np.concatenate(all_yp) if all_yp else np.zeros(1)
        pooled_sp = (
            float(scipy_stats.spearmanr(yt_pool, yp_pool).correlation)
            if np.std(yt_pool) > 1e-9 and np.std(yp_pool) > 1e-9
            else float("nan")
        )
        pooled_pe = (
            float(np.corrcoef(yt_pool, yp_pool)[0, 1])
            if np.std(yt_pool) > 1e-9 and np.std(yp_pool) > 1e-9
            else float("nan")
        )
        pooled_mae = float(np.mean(np.abs(yt_pool - yp_pool)))
        pooled_rmse = float(np.sqrt(np.mean((yt_pool - yp_pool) ** 2)))

        rng = np.random.default_rng(seed)
        n_p = len(rhos)
        idx_mat = rng.integers(0, n_p, size=(n_boot, n_p))
        boot_med_sp = np.median(rhos[idx_mat], axis=1)
        boot_mean_sp = np.mean(rhos[idx_mat], axis=1)
        boot_mean_pe = np.mean(rs[idx_mat], axis=1)

        summary = {
            "n_proteins_total": int(len(protein_ids)),
            "n_proteins_evaluated": int(n_p),
            "n_proteins_excluded_invalid_corr": int(len(excluded_proteins)),
            "excluded_protein_ids": excluded_proteins,
            "n_variants_evaluated": int(len(yt_pool)),
            "median_spearman": round(float(np.median(rhos)), 4),
            "median_spearman_ci95_low": round(float(np.quantile(boot_med_sp, 0.025)), 4),
            "median_spearman_ci95_high": round(float(np.quantile(boot_med_sp, 0.975)), 4),
            "mean_spearman": round(float(np.mean(rhos)), 4),
            "mean_spearman_ci95_low": round(float(np.quantile(boot_mean_sp, 0.025)), 4),
            "mean_spearman_ci95_high": round(float(np.quantile(boot_mean_sp, 0.975)), 4),
            "mean_pearson": round(float(np.mean(rs)), 4),
            "mean_pearson_ci95_low": round(float(np.quantile(boot_mean_pe, 0.025)), 4),
            "mean_pearson_ci95_high": round(float(np.quantile(boot_mean_pe, 0.975)), 4),
            "mean_mae": round(float(np.mean(maes)), 4),
            "mean_rmse": round(float(np.mean(rmses)), 4),
            "pooled_spearman": round(pooled_sp, 4) if np.isfinite(pooled_sp) else None,
            "pooled_pearson": round(pooled_pe, 4) if np.isfinite(pooled_pe) else None,
            "pooled_mae": round(pooled_mae, 4),
            "pooled_rmse": round(pooled_rmse, 4),
        }
        return summary, prot_df

    def assert_identical_evaluation_variants(
        prot_df_a: pd.DataFrame,
        prot_df_b: pd.DataFrame,
        mask_a: np.ndarray,
        mask_b: np.ndarray,
        protein_ids_a: np.ndarray,
        protein_ids_b: np.ndarray,
    ) -> Tuple[int, int]:
        """Fix 15 & Fix 29: Verify matching protein IDs, residue numbering, mutation identities,
        and valid-label masks before calculating paired metrics.
        """
        if not np.array_equal(protein_ids_a, protein_ids_b):
            raise ValueError("Paired comparison failed: protein_ids arrays do not match in order and identity!")
        if not np.array_equal(mask_a, mask_b):
            raise ValueError("Paired comparison failed: mutation label_mask arrays are not identical!")
        pids_df_a = prot_df_a["protein_id"].astype(str).tolist()
        pids_df_b = prot_df_b["protein_id"].astype(str).tolist()
        if pids_df_a != pids_df_b:
            raise ValueError(
                f"Paired comparison failed: evaluated proteins differ ({len(pids_df_a)} vs {len(pids_df_b)})!"
            )
        if not np.array_equal(prot_df_a["n_variants"].to_numpy(), prot_df_b["n_variants"].to_numpy()):
            raise ValueError("Paired comparison failed: per-protein variant counts differ!")
        return len(pids_df_a), int(np.sum(mask_a))

    def paired_bootstrap_test_on_identical_variants(
        prot_df_model: pd.DataFrame,
        prot_df_ref: pd.DataFrame,
        mask_model: np.ndarray,
        mask_ref: np.ndarray,
        protein_ids: np.ndarray,
        metric_col: str = "spearman_rho",
        n_boot: int = 10000,
        seed: int = 42,
    ) -> Dict[str, Any]:
        """Fix 15, 29, 30, 31: Paired protein-level bootstrap CI and Wilcoxon signed-rank test
        after asserting 100% identical proteins and variants.
        """
        n_paired_prots, n_paired_vars = assert_identical_evaluation_variants(
            prot_df_model, prot_df_ref, mask_model, mask_ref, protein_ids, protein_ids
        )
        merged = pd.merge(
            prot_df_model[["protein_id", "n_variants", metric_col]],
            prot_df_ref[["protein_id", metric_col]],
            on="protein_id",
            suffixes=("_model", "_ref"),
        ).sort_values("protein_id")
        v_m = merged[f"{metric_col}_model"].to_numpy(dtype=np.float64)
        v_r = merged[f"{metric_col}_ref"].to_numpy(dtype=np.float64)
        diffs = v_m - v_r

        n_p = len(diffs)
        rng = np.random.default_rng(seed)
        idx_mat = rng.integers(0, n_p, size=(n_boot, n_p))
        boot_delta_med = np.median(v_m[idx_mat], axis=1) - np.median(v_r[idx_mat], axis=1)
        boot_delta_mean = np.mean(diffs[idx_mat], axis=1)

        try:
            if np.allclose(diffs, 0.0):
                wilcoxon_p = 1.0
            else:
                wilcoxon_p = float(scipy_stats.wilcoxon(v_m, v_r, zero_method="zsplit").pvalue)
        except Exception:
            wilcoxon_p = 1.0

        ci_lo = float(np.quantile(boot_delta_med, 0.025))
        ci_hi = float(np.quantile(boot_delta_med, 0.975))
        return {
            "n_paired_proteins": n_paired_prots,
            "n_paired_variants": n_paired_vars,
            "delta_median_spearman": round(float(np.median(v_m) - np.median(v_r)), 4),
            "delta_median_ci95_low": round(ci_lo, 4),
            "delta_median_ci95_high": round(ci_hi, 4),
            "delta_mean_spearman": round(float(np.mean(diffs)), 4),
            "delta_mean_ci95_low": round(float(np.quantile(boot_delta_mean, 0.025)), 4),
            "delta_mean_ci95_high": round(float(np.quantile(boot_delta_mean, 0.975)), 4),
            "wilcoxon_p_value": round(wilcoxon_p, 5),
            "statistically_resolvable_95ci": bool(ci_lo > 0.0 or ci_hi < 0.0),
        }

    class HillClimbTracker:
        """Priority 0 Fix 1 & Priority 4 Fixes 27, 28:
        - `log_validation_step()` accepts ONLY validation predictions (`val_preds`) and a lazy
          `test_eval_closure` callable. It NEVER accepts or computes test predictions during hill climbing!
        - `lock_validation_selection()` selects the best sequence-only and best structure-adapter
          configurations strictly on validation median per-protein Spearman and writes
          `selected_model_before_test.json` BEFORE opening the test set.
        - `evaluate_locked_selection_on_test_once()` evaluates ONLY the locked validation winner(s)
          and pre-registered baselines on the 28 test proteins once.
        """

        def __init__(self, result_status_default: str = "measured") -> None:
            self.result_status_default = result_status_default
            self.validation_rows: List[Dict[str, Any]] = []
            self.entries_by_id: Dict[str, Dict[str, Any]] = {}
            self.selection_locked: bool = False
            self.locked_selection_manifest: Dict[str, Any] = {}

        def log_validation_step(
            self,
            step_id: str,
            architecture_track: str,
            regime: str,
            model_family: str,
            finetune_mode: str,
            loss_fn: str,
            lora_rank: int,
            backbone_lr: float,
            head_lr: float,
            seeds: List[int],
            per_seed_val_medians: List[float],
            checkpoint_paths: List[str],
            val_preds: np.ndarray,
            val_tensors: Dict[str, np.ndarray],
            test_eval_closure: Callable[[Dict[str, np.ndarray], np.ndarray, np.ndarray], np.ndarray],
            is_preregistered_baseline: bool = False,
            result_status: Optional[str] = None,
            notes: str = "",
        ) -> Dict[str, Any]:
            if self.selection_locked:
                raise RuntimeError("Cannot log new hill-climb steps after validation selection has been locked!")
            if not callable(test_eval_closure):
                raise TypeError("test_eval_closure must be a lazy callable (never precomputed test_preds)!")

            val_summary, val_prot_df = evaluate_split_with_bootstrap_ci(
                val_tensors["y_target"],
                val_preds,
                val_tensors["label_mask"],
                val_tensors["protein_ids"],
                n_boot=2000,
                seed=seeds[0] if seeds else 42,
            )
            seed_mean = round(float(np.mean(per_seed_val_medians)), 4) if per_seed_val_medians else val_summary["median_spearman"]
            seed_std = round(float(np.std(per_seed_val_medians)), 4) if len(per_seed_val_medians) > 1 else 0.0
            eff_status = result_status if result_status is not None else self.result_status_default

            row = {
                "step_id": step_id,
                "result_status": eff_status,
                "architecture_track": architecture_track,
                "regime": regime,
                "model_family": model_family,
                "finetune_mode": finetune_mode,
                "loss_fn": loss_fn,
                "lora_rank": lora_rank,
                "backbone_lr": backbone_lr,
                "head_lr": head_lr,
                "seeds": ",".join(str(s) for s in seeds),
                "seed_mean_val_median_spearman": seed_mean,
                "seed_std_val_median_spearman": seed_std,
                "checkpoint_metric": "val_median_spearman_rho",
                "val_n_proteins_evaluated": val_summary["n_proteins_evaluated"],
                "val_n_proteins_excluded": val_summary["n_proteins_excluded_invalid_corr"],
                "val_n_variants_evaluated": val_summary["n_variants_evaluated"],
                "val_median_spearman": val_summary["median_spearman"],
                "val_median_spearman_ci95": f"[{val_summary['median_spearman_ci95_low']:.4f}, {val_summary['median_spearman_ci95_high']:.4f}]",
                "val_mean_spearman": val_summary["mean_spearman"],
                "val_pooled_spearman": val_summary["pooled_spearman"],
                "val_pooled_pearson": val_summary["pooled_pearson"],
                "val_pooled_mae": val_summary["pooled_mae"],
                "val_pooled_rmse": val_summary["pooled_rmse"],
                "checkpoint_paths": ";".join(checkpoint_paths),
                "notes": notes,
            }
            self.validation_rows.append(row)
            self.entries_by_id[step_id] = {
                "meta": row,
                "is_preregistered_baseline": is_preregistered_baseline,
                "val_summary": val_summary,
                "val_prot_df": val_prot_df,
                "test_eval_closure": test_eval_closure,
            }
            print(
                f"[Hill-Climb Val-Only {step_id}] ({eff_status}) {model_family} [{architecture_track}] "
                f"-> Val Median Spearman = {val_summary['median_spearman']:.4f} {row['val_median_spearman_ci95']} "
                f"(seed mean±std = {seed_mean:.4f}±{seed_std:.4f}, n_prot={val_summary['n_proteins_evaluated']}/{val_summary['n_proteins_total']})"
            )
            return row

        def get_validation_log_df(self) -> pd.DataFrame:
            return pd.DataFrame(self.validation_rows)

        def lock_validation_selection(self, out_dir: Path) -> Dict[str, Any]:
            """Fix 1 & Fix 28: Select the winning validation configuration per track (`sequence_only_esm2`
            and `structure_adapter_esm2_proteinmpnn`) strictly on `val_median_spearman` and write
            `selected_model_before_test.json` to disk BEFORE opening the test set.
            """
            seq_candidates = [
                r
                for r in self.validation_rows
                if r["architecture_track"] == "sequence_only_esm2"
                and r["regime"] == "benchmark_all_239"
                and not self.entries_by_id[r["step_id"]]["is_preregistered_baseline"]
            ]
            struct_candidates = [
                r
                for r in self.validation_rows
                if r["architecture_track"] == "structure_adapter_esm2_proteinmpnn"
                and r["regime"] == "benchmark_all_239"
                and not self.entries_by_id[r["step_id"]]["is_preregistered_baseline"]
            ]
            filt30_candidates = [
                r for r in self.validation_rows if r["regime"] == "leak_filtered_0.30"
            ]
            filt25_candidates = [
                r for r in self.validation_rows if r["regime"] == "leak_filtered_0.25"
            ]

            best_seq = max(seq_candidates, key=lambda r: float(r["val_median_spearman"])) if seq_candidates else None
            best_struct = (
                max(struct_candidates, key=lambda r: float(r["val_median_spearman"]))
                if struct_candidates
                else None
            )
            best_overall_trainable = (
                max(seq_candidates + struct_candidates, key=lambda r: float(r["val_median_spearman"]))
                if (seq_candidates or struct_candidates)
                else None
            )
            best_filt30 = max(filt30_candidates, key=lambda r: float(r["val_median_spearman"])) if filt30_candidates else None
            best_filt25 = max(filt25_candidates, key=lambda r: float(r["val_median_spearman"])) if filt25_candidates else None

            self.selection_locked = True
            self.locked_selection_manifest = {
                "locked_before_test_evaluation": True,
                "selection_criterion": "val_median_spearman_rho (validation split only; test split untouched)",
                "n_total_validation_experiments_logged": len(self.validation_rows),
                "selected_sequence_only_winner": best_seq,
                "selected_structure_adapter_winner": best_struct,
                "selected_overall_winner": best_overall_trainable,
                "selected_leak_filtered_30pct_winner": best_filt30,
                "selected_leak_filtered_25pct_winner": best_filt25,
            }
            sel_path = out_dir / "selected_model_before_test.json"
            sel_path.write_text(
                json.dumps(self.locked_selection_manifest, indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            print(
                f"[Validation Selection Locked -> {sel_path.name}] "
                f"Selected Sequence-Only Winner: {best_seq['step_id'] if best_seq else 'none'} "
                f"(Val Med Spearman={best_seq['val_median_spearman'] if best_seq else 'N/A'}) | "
                f"Selected Structure-Adapter Winner: {best_struct['step_id'] if best_struct else 'none'} "
                f"(Val Med Spearman={best_struct['val_median_spearman'] if best_struct else 'N/A'})."
            )
            return self.locked_selection_manifest

