    def validate_structure_inputs(
        proteins_df: pd.DataFrame,
        tensors_by_split: Dict[str, Dict[str, np.ndarray]],
    ) -> Dict[str, Any]:
        """Fix 9: Check residue-to-coordinate mapping, missing atoms, chain selection,
        sequence alignment, and coordinate validity across train, val, and test splits.
        """
        per_split: Dict[str, Any] = {}
        req_prot_cols = {
            "protein_id",
            "split",
            "sequence",
            "length",
            "structure_status",
            "pdb_chain",
            "pdb_seq_identity",
            "pdb_offset",
            "pdb_gaps",
            "n_valid_backbone_res",
        }
        missing_cols = req_prot_cols - set(proteins_df.columns)
        if missing_cols:
            raise ValueError(f"proteins_df is missing required structure audit columns: {sorted(missing_cols)}")

        for sp in ("train", "val", "test"):
            td = tensors_by_split[sp]
            sp_prots = (
                proteins_df[proteins_df["split"] == sp]
                .set_index("protein_id")
                .loc[td["protein_ids"]]
                .reset_index()
            )
            lengths = td["lengths"]
            coords = td["backbone_coords"]  # [N, Lmax, 4, 3] for (N, CA, C, O)
            vmask = td["residue_valid_mask"]  # [N, Lmax]
            N, Lmax = vmask.shape

            if coords.shape != (N, Lmax, 4, 3):
                raise ValueError(f"Invalid backbone_coords shape on {sp}: {coords.shape} != {(N, Lmax, 4, 3)}")

            total_res = int(np.sum(lengths))
            valid_res = 0
            unmasked_nan_violations = 0
            padding_valid_violations = 0
            ca_ca_dists: List[np.ndarray] = []
            n_ca_dists: List[np.ndarray] = []
            status_counts = sp_prots["structure_status"].astype(str).value_counts().to_dict()
            chains_selected = sp_prots["pdb_chain"].fillna("NONE").astype(str).value_counts().to_dict()
            min_seq_id = float(sp_prots["pdb_seq_identity"].min())

            for i in range(N):
                L = int(lengths[i])
                vm = vmask[i, :L]
                valid_res += int(np.sum(vm))
                if L < Lmax and np.any(vmask[i, L:]):
                    padding_valid_violations += int(np.sum(vmask[i, L:]))
                # Wherever residue_valid_mask is True, all 4 backbone atoms (N, CA, C, O) must be finite
                if np.any(vm):
                    c_val = coords[i, :L][vm]  # [n_val, 4, 3]
                    if not np.all(np.isfinite(c_val)):
                        unmasked_nan_violations += int(np.sum(~np.isfinite(c_val)))
                    n_ca = np.linalg.norm(c_val[:, 1, :] - c_val[:, 0, :], axis=-1)
                    n_ca_dists.append(n_ca)
                if L > 1:
                    ca = coords[i, :L, 1, :]
                    consec = vm[:-1] & vm[1:]
                    if np.any(consec):
                        d = np.linalg.norm(ca[1:][consec] - ca[:-1][consec], axis=-1)
                        ca_ca_dists.append(d)

            if unmasked_nan_violations > 0 or padding_valid_violations > 0 or min_seq_id < 0.95:
                raise RuntimeError(
                    f"STRUCTURE INPUT VALIDATION FAILED on split={sp}: "
                    f"unmasked_nan_atoms={unmasked_nan_violations}, padding_valid_violations={padding_valid_violations}, "
                    f"min_pdb_seq_identity={min_seq_id:.4f}"
                )

            all_ca_d = np.concatenate(ca_ca_dists) if ca_ca_dists else np.array([3.8], dtype=np.float32)
            all_nca_d = np.concatenate(n_ca_dists) if n_ca_dists else np.array([1.46], dtype=np.float32)
            per_split[sp] = {
                "n_proteins": N,
                "total_residues": total_res,
                "valid_backbone_residues": valid_res,
                "valid_backbone_pct": round(100.0 * valid_res / max(1, total_res), 2),
                "structure_status_counts": status_counts,
                "chains_selected_counts": chains_selected,
                "min_pdb_seq_identity": round(min_seq_id, 4),
                "ca_ca_bond_median_A": round(float(np.median(all_ca_d)), 3),
                "n_ca_bond_median_A": round(float(np.median(all_nca_d)), 3),
                "unmasked_nan_atom_violations": unmasked_nan_violations,
                "padding_valid_violations": padding_valid_violations,
            }

        print(
            f"[Structure Input Validation - PASS] All splits verified: "
            f"train valid={per_split['train']['valid_backbone_pct']}%, "
            f"val valid={per_split['val']['valid_backbone_pct']}%, "
            f"test valid={per_split['test']['valid_backbone_pct']}%, "
            f"CA-CA median={per_split['train']['ca_ca_bond_median_A']} A, 0 NaN atom leaks."
        )
        return {"status": "PASS", "per_split": per_split}

    def extract_per_residue_3d_env_features(
        seq_indices: np.ndarray,
        lengths: np.ndarray,
        backbone_coords: np.ndarray,
        residue_valid_mask: np.ndarray,
    ) -> np.ndarray:
        """Extract 29-dim hand-crafted 3D structural microenvironment features `[N, Lmax, 29]`
        strictly for the `Ridge_HandCrafted3D` non-pretrained reference baseline (and optional ablation).
        Never labeled as ProteinMPNN.
        """
        N, Lmax = seq_indices.shape
        out = np.zeros((N, Lmax, 29), dtype=np.float32)
        rbf_centers = np.linspace(3.5, 14.5, 7, dtype=np.float32)

        for p_idx in range(N):
            L = int(lengths[p_idx])
            if L <= 0:
                continue
            s_idx = np.clip(seq_indices[p_idx, :L], 0, 19)
            coords = backbone_coords[p_idx, :L]
            vmask = residue_valid_mask[p_idx, :L]

            pos_norm = np.linspace(0.0, 1.0, L, dtype=np.float32)
            term_ind = np.minimum(np.arange(L), np.arange(L - 1, -1, -1)) / 5.0
            term_ind = np.clip(term_ind, 0.0, 1.0).astype(np.float32)

            res_props = AA_PROPS[s_idx]
            pad_props = np.pad(res_props, ((2, 2), (0, 0)), mode="edge")
            win_props = (
                pad_props[0:L] + pad_props[1 : L + 1] + pad_props[2 : L + 2] + pad_props[3 : L + 3] + pad_props[4 : L + 4]
            ) / 5.0

            ca = coords[:, 1, :].copy()
            n_at = coords[:, 0, :].copy()
            c_at = coords[:, 2, :].copy()
            if not np.all(vmask):
                ca[~vmask] = 0.0
                n_at[~vmask] = 0.0
                c_at[~vmask] = 0.0

            diff = ca[:, None, :] - ca[None, :, :]
            dist_mat = np.linalg.norm(diff, axis=-1).astype(np.float32)
            pair_valid = vmask[:, None] & vmask[None, :]
            np.fill_diagonal(pair_valid, False)
            dist_masked = np.where(pair_valid, dist_mat, 999.0)

            cn8 = np.sum(dist_masked < 8.0, axis=-1).astype(np.float32) / 12.0
            cn10 = np.sum(dist_masked < 10.0, axis=-1).astype(np.float32) / 20.0
            cn12 = np.sum(dist_masked < 12.0, axis=-1).astype(np.float32) / 30.0
            w_contact = np.where(pair_valid, np.exp(-((dist_mat / 9.0) ** 2)), 0.0).astype(np.float32)
            burial = np.sum(w_contact, axis=-1) / 15.0

            centroid = np.mean(ca[vmask], axis=0) if np.any(vmask) else np.zeros(3, dtype=np.float32)
            dist_cent = np.where(vmask, np.linalg.norm(ca - centroid[None, :], axis=-1) / 15.0, 0.0)

            d_prev = np.zeros(L, dtype=np.float32)
            d_next = np.zeros(L, dtype=np.float32)
            if L > 1:
                d_prev[1:] = np.linalg.norm(ca[1:] - ca[:-1], axis=-1) / 3.8
                d_next[:-1] = d_prev[1:]

            u1 = n_at - ca
            u2 = c_at - ca
            u1 /= np.linalg.norm(u1, axis=-1, keepdims=True) + 1e-6
            u2 /= np.linalg.norm(u2, axis=-1, keepdims=True) + 1e-6
            u3 = np.cross(u1, u2)
            u3 /= np.linalg.norm(u3, axis=-1, keepdims=True) + 1e-6
            v_cb = -0.58 * (u1 + u2) + 0.81 * u3
            v_cb /= np.linalg.norm(v_cb, axis=-1, keepdims=True) + 1e-6
            cent_dir = ca - centroid[None, :]
            cent_dir /= np.linalg.norm(cent_dir, axis=-1, keepdims=True) + 1e-6
            cb_out_dot = np.sum(v_cb * cent_dir, axis=-1).astype(np.float32)

            w_norm = w_contact / (np.sum(w_contact, axis=-1, keepdims=True) + 1e-6)
            spatial_props = w_norm @ res_props

            rbf_feats = np.zeros((L, 7), dtype=np.float32)
            for r_i, rc in enumerate(rbf_centers):
                rbf_w = np.where(pair_valid, np.exp(-0.5 * ((dist_mat - rc) ** 2)), 0.0)
                rbf_feats[:, r_i] = np.sum(rbf_w, axis=-1) / 10.0

            torsion = np.zeros((L, 4), dtype=np.float32)
            if L >= 4:
                v_step = ca[1:] - ca[:-1]
                v_step /= np.linalg.norm(v_step, axis=-1, keepdims=True) + 1e-6
                cos_ang = np.sum(-v_step[:-1] * v_step[1:], axis=-1)
                sin_ang = np.linalg.norm(np.cross(-v_step[:-1], v_step[1:]), axis=-1)
                torsion[1 : L - 1, 0] = cos_ang
                torsion[1 : L - 1, 1] = sin_ang

            out[p_idx, :L] = np.concatenate(
                [
                    pos_norm[:, None],
                    term_ind[:, None],
                    win_props,
                    np.stack([cn8, cn10, cn12, burial], axis=-1),
                    np.stack([dist_cent, d_prev, d_next, cb_out_dot], axis=-1),
                    spatial_props,
                    rbf_feats,
                    torsion,
                ],
                axis=-1,
            )
        return out

    def fit_and_predict_ridge_handcrafted_3d_baseline(
        train_tensors: Dict[str, np.ndarray],
        train_env_3d: np.ndarray,
        eval_splits: Dict[str, Tuple[Dict[str, np.ndarray], np.ndarray]],
        train_protein_mask: Optional[np.ndarray] = None,
        l2_alpha: float = 150.0,
    ) -> Tuple[Dict[str, np.ndarray], Callable[[Dict[str, np.ndarray], np.ndarray], np.ndarray]]:
        """Non-pretrained reference baseline (`Ridge_HandCrafted3D`).
        During validation hill-climbing, `eval_splits` contains ONLY `train` and `val` (never `test`).
        Returns `(preds_by_split, predict_split_fn)` so test evaluation can be called once at the end.
        """
        eye20 = np.eye(20, dtype=np.float32)

        def _build_variant_design_matrix(
            seq_idx: np.ndarray,
            env_3d: np.ndarray,
            p_indices: np.ndarray,
            pos_indices: np.ndarray,
            mut_indices: np.ndarray,
        ) -> np.ndarray:
            wt_idx = seq_idx[p_indices, pos_indices]
            env = env_3d[p_indices, pos_indices]
            wt_1h = eye20[wt_idx]
            mut_1h = eye20[mut_indices]
            blosum_s = BLOSUM62_MAT[wt_idx, mut_indices][:, None] / 10.0
            d_props = AA_PROPS[mut_indices] - AA_PROPS[wt_idx]
            wt_p = AA_PROPS[wt_idx]
            mut_p = AA_PROPS[mut_indices]
            burial = env[:, 9:10]
            cn8 = env[:, 6:7]
            cb_dot = env[:, 13:14]
            inter = np.concatenate(
                [
                    burial * d_props,
                    cn8 * d_props,
                    cb_dot * d_props,
                    burial * blosum_s,
                    env[:, 14:18] * d_props,
                ],
                axis=-1,
            )
            return np.concatenate([env, wt_1h, mut_1h, blosum_s, wt_p, mut_p, d_props, inter], axis=-1)

        t_mask = train_tensors["label_mask"].copy()
        if train_protein_mask is not None:
            t_mask = t_mask & train_protein_mask[:, None, None]

        p_tr, pos_tr, mut_tr = np.where(t_mask)
        X_tr = _build_variant_design_matrix(
            train_tensors["seq_indices"], train_env_3d, p_tr, pos_tr, mut_tr
        )
        y_tr = train_tensors["y_target"][p_tr, pos_tr, mut_tr].astype(np.float64)

        X_tr_aug = np.hstack([X_tr.astype(np.float64), np.ones((len(X_tr), 1), dtype=np.float64)])
        D = X_tr_aug.shape[1]
        reg = np.eye(D, dtype=np.float64) * float(l2_alpha)
        reg[-1, -1] = 0.0
        w = np.linalg.solve(X_tr_aug.T @ X_tr_aug + reg, X_tr_aug.T @ y_tr).astype(np.float32)

        def _predict_split(sp_tensors: Dict[str, np.ndarray], sp_env: np.ndarray) -> np.ndarray:
            N, Lmax = sp_tensors["seq_indices"].shape
            pred_grid = np.zeros((N, Lmax, 20), dtype=np.float32)
            p_ev, pos_ev, mut_ev = np.where(sp_tensors["label_mask"])
            if len(p_ev) > 0:
                X_ev = _build_variant_design_matrix(
                    sp_tensors["seq_indices"], sp_env, p_ev, pos_ev, mut_ev
                )
                pred_vals = X_ev @ w[:-1] + w[-1]
                pred_grid[p_ev, pos_ev, mut_ev] = pred_vals
            return pred_grid

        preds_out = {
            sp_name: _predict_split(sp_t, sp_e) for sp_name, (sp_t, sp_e) in eval_splits.items()
        }
        return preds_out, _predict_split

