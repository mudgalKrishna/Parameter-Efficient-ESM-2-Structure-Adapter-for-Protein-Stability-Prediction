    def compute_validation_median_spearman(
        y_true_grid: np.ndarray,
        y_pred_grid: np.ndarray,
        label_mask_grid: np.ndarray,
        protein_ids: Optional[np.ndarray] = None,
    ) -> Tuple[float, int, int, List[str]]:
        """Fix 17 & Fix 18: Compute median per-protein Spearman rank correlation transparently.
        Never replaces constant or undefined predictions with 0.0 correlation!
        Returns `(median_spearman, n_evaluated, n_excluded, excluded_protein_ids)`.
        """
        rhos: List[float] = []
        excluded_pids: List[str] = []
        N = y_true_grid.shape[0]
        for i in range(N):
            pid_str = str(protein_ids[i]) if protein_ids is not None else f"prot_{i}"
            m = label_mask_grid[i]
            if int(np.sum(m)) < 3:
                excluded_pids.append(f"{pid_str}(<3_variants)")
                continue
            yt = y_true_grid[i][m].astype(np.float64)
            yp = y_pred_grid[i][m].astype(np.float64)
            if not (np.all(np.isfinite(yt)) and np.all(np.isfinite(yp))):
                excluded_pids.append(f"{pid_str}(non_finite)")
                continue
            if np.std(yt) <= 1e-9 or np.std(yp) <= 1e-9:
                excluded_pids.append(f"{pid_str}(constant_pred_or_target)")
                continue
            rho = float(scipy_stats.spearmanr(yt, yp).correlation)
            if np.isfinite(rho):
                rhos.append(rho)
            else:
                excluded_pids.append(f"{pid_str}(nan_spearman)")

        med_rho = float(np.median(rhos)) if rhos else float("nan")
        return med_rho, len(rhos), len(excluded_pids), excluded_pids

