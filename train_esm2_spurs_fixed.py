        class LoRALinear(nn.Module):
            """Dependency-free Low-Rank Adaptation wrapper around an existing `nn.Linear` layer."""

            def __init__(
                self,
                base_linear: nn.Linear,
                rank: int = 8,
                alpha: float = 16.0,
                dropout: float = 0.05,
            ) -> None:
                super().__init__()
                self.base_linear = base_linear
                for p in self.base_linear.parameters():
                    p.requires_grad = False
                self.in_features = base_linear.in_features
                self.out_features = base_linear.out_features
                self.rank = int(rank)
                self.scaling = float(alpha) / float(max(1, rank))
                self.dropout = nn.Dropout(float(dropout)) if dropout > 0.0 else nn.Identity()
                self.lora_A = nn.Parameter(
                    torch.empty(
                        (self.rank, self.in_features),
                        dtype=base_linear.weight.dtype,
                        device=base_linear.weight.device,
                    )
                )
                self.lora_B = nn.Parameter(
                    torch.zeros(
                        (self.out_features, self.rank),
                        dtype=base_linear.weight.dtype,
                        device=base_linear.weight.device,
                    )
                )
                nn.init.kaiming_uniform_(self.lora_A, a=math.sqrt(5))

            def forward(self, x: torch.Tensor) -> torch.Tensor:
                base_out = self.base_linear(x)
                lora_out = F.linear(F.linear(self.dropout(x), self.lora_A), self.lora_B) * self.scaling
                return base_out + lora_out

        def inject_lora_into_esm_backbone(
            esm_model: nn.Module,
            rank: int = 8,
            alpha: float = 16.0,
            dropout: float = 0.05,
            target_suffixes: Tuple[str, ...] = ("query", "key", "value", "dense"),
        ) -> Tuple[int, List[str]]:
            """Replace target Linear layers in ESM-2 encoder layers with LoRALinear adapters."""
            replaced_names: List[str] = []
            for parent_name, parent_mod in list(esm_model.named_modules()):
                if ".layer." not in parent_name and not parent_name.startswith("esm.encoder.layer"):
                    continue
                for child_name, child_mod in list(parent_mod.named_children()):
                    if isinstance(child_mod, nn.Linear) and child_name in target_suffixes:
                        setattr(
                            parent_mod,
                            child_name,
                            LoRALinear(child_mod, rank=rank, alpha=alpha, dropout=dropout),
                        )
                        replaced_names.append(f"{parent_name}.{child_name}")
            return len(replaced_names), replaced_names

        class ProteinMPNNEncoderLayer(nn.Module):
            """Single message-passing layer matching the official ProteinMPNN `EncLayer` architecture
            (`W1, W2, W3, norm1, norm2, W11, W12, W13, norm3`).
            """

            def __init__(self, hidden_dim: int = 128, dropout: float = 0.1) -> None:
                super().__init__()
                self.hidden_dim = hidden_dim
                self.W1 = nn.Linear(hidden_dim * 3, hidden_dim, bias=True)
                self.W2 = nn.Linear(hidden_dim, hidden_dim, bias=True)
                self.W3 = nn.Linear(hidden_dim, hidden_dim, bias=True)
                self.W11 = nn.Linear(hidden_dim * 3, hidden_dim, bias=True)
                self.W12 = nn.Linear(hidden_dim, hidden_dim, bias=True)
                self.W13 = nn.Linear(hidden_dim, hidden_dim, bias=True)
                self.norm1 = nn.LayerNorm(hidden_dim)
                self.norm2 = nn.LayerNorm(hidden_dim)
                self.norm3 = nn.LayerNorm(hidden_dim)
                self.dropout = nn.Dropout(dropout)
                self.dense = nn.Sequential(
                    nn.Linear(hidden_dim, hidden_dim * 4),
                    nn.GELU(),
                    nn.Dropout(dropout),
                    nn.Linear(hidden_dim * 4, hidden_dim),
                )
                self.act = nn.GELU()

            def forward(
                self,
                h_V: torch.Tensor,
                h_E: torch.Tensor,
                E_idx: torch.Tensor,
                mask_V: torch.Tensor,
                mask_bw: torch.Tensor,
            ) -> Tuple[torch.Tensor, torch.Tensor]:
                B, L, K = E_idx.shape
                D = h_V.shape[-1]
                # Gather neighbor node features h_V_j: [B, L, K, D]
                flat_idx = E_idx.reshape(B, L * K, 1).expand(-1, -1, D)
                h_V_neighbors = torch.gather(h_V, dim=1, index=flat_idx).reshape(B, L, K, D)
                h_V_center = h_V.unsqueeze(2).expand(-1, -1, K, -1)

                h_EV = torch.cat([h_V_center, h_E, h_V_neighbors], dim=-1)
                h_msg = self.W3(self.act(self.W2(self.act(self.W1(h_EV)))))
                h_msg = h_msg * mask_bw.unsqueeze(-1)
                dh = torch.sum(h_msg, dim=2) / math.sqrt(float(max(1, K)))
                h_V = self.norm1(h_V + self.dropout(dh))
                h_V = h_V * mask_V.unsqueeze(-1)

                dh_ffn = self.dense(h_V)
                h_V = self.norm2(h_V + self.dropout(dh_ffn))
                h_V = h_V * mask_V.unsqueeze(-1)

                # Edge update
                h_V_neighbors2 = torch.gather(h_V, dim=1, index=flat_idx).reshape(B, L, K, D)
                h_V_center2 = h_V.unsqueeze(2).expand(-1, -1, K, -1)
                h_EV2 = torch.cat([h_V_center2, h_E, h_V_neighbors2], dim=-1)
                h_E_msg = self.W13(self.act(self.W12(self.act(self.W11(h_EV2)))))
                h_E = self.norm3(h_E + self.dropout(h_E_msg)) * mask_bw.unsqueeze(-1)
                return h_V, h_E

        class ProteinMPNNStructureEncoder(nn.Module):
            """Fix 6: Pretrained ProteinMPNN 3D structure encoder processing backbone coordinates
            `[B, L, 4, 3]` (`N, CA, C, O` in Å) and `residue_valid_mask` `[B, L]`.
            Reconstructs virtual CB, builds a masked k-NN spatial graph, extracts 400-dim 25-pair
            Gaussian RBF distances + 65-dim relative positional encodings, and runs 3 message-passing
            encoder layers to produce per-residue structural representations `h_struct` (`[B, L, 128]`).
            """

            def __init__(
                self,
                hidden_dim: int = 128,
                num_encoder_layers: int = 3,
                k_neighbors: int = 30,
                num_rbf: int = 16,
                dropout: float = 0.1,
            ) -> None:
                super().__init__()
                self.hidden_dim = hidden_dim
                self.k_neighbors = k_neighbors
                self.num_rbf = num_rbf
                # 25 atom pairs (N, CA, C, O, CB) x 16 RBF bins = 400 + 65 relative pos bins = 465
                self.edge_in_dim = 25 * num_rbf + 65
                self.edge_embedding = nn.Linear(self.edge_in_dim, hidden_dim, bias=False)
                self.norm_edges = nn.LayerNorm(hidden_dim)
                self.W_e = nn.Linear(hidden_dim, hidden_dim, bias=True)
                self.encoder_layers = nn.ModuleList(
                    [ProteinMPNNEncoderLayer(hidden_dim=hidden_dim, dropout=dropout) for _ in range(num_encoder_layers)]
                )
                self.register_buffer("rbf_centers", torch.linspace(2.0, 22.0, num_rbf))
                self.rbf_sigma = (22.0 - 2.0) / float(num_rbf)

            def _featurize_backbone_graph(
                self,
                backbone_coords: torch.Tensor,
                residue_valid_mask: torch.Tensor,
            ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
                B, L, _, _ = backbone_coords.shape
                K = min(self.k_neighbors, L)
                coords = torch.nan_to_num(backbone_coords, nan=0.0)
                N_at = coords[:, :, 0, :]
                CA_at = coords[:, :, 1, :]
                C_at = coords[:, :, 2, :]
                O_at = coords[:, :, 3, :]

                # Virtual CB reconstruction (Dauparas et al. Science 2022)
                b_vec = CA_at - N_at
                c_vec = C_at - CA_at
                a_vec = torch.cross(b_vec, c_vec, dim=-1)
                CB_at = -0.58273431 * a_vec + 0.56802827 * b_vec - 0.54067466 * c_vec + CA_at

                atoms_5 = torch.stack([CA_at, N_at, C_at, O_at, CB_at], dim=2)  # [B, L, 5, 3]
                vmask_f = residue_valid_mask.float()
                pair_valid = vmask_f.unsqueeze(2) * vmask_f.unsqueeze(1)  # [B, L, L]

                ca_diff = CA_at.unsqueeze(2) - CA_at.unsqueeze(1)
                ca_dist = torch.sqrt(torch.sum(ca_diff * ca_diff, dim=-1) + 1e-6)
                ca_dist_masked = torch.where(pair_valid > 0.5, ca_dist, torch.full_like(ca_dist, 1e6))

                _, E_idx = torch.topk(ca_dist_masked, k=K, dim=-1, largest=False)  # [B, L, K]
                mask_bw = torch.gather(pair_valid, dim=2, index=E_idx)  # [B, L, K]

                # Gather 5-atom coordinates of neighbors: [B, L, K, 5, 3]
                flat_e = E_idx.reshape(B, L * K, 1, 1).expand(-1, -1, 5, 3)
                neigh_atoms = torch.gather(atoms_5, dim=1, index=flat_e).reshape(B, L, K, 5, 3)
                center_atoms = atoms_5.unsqueeze(2).expand(-1, -1, K, -1, -1)

                # All 25 pairwise distances: [B, L, K, 5, 5] -> [B, L, K, 25]
                diff_25 = center_atoms.unsqueeze(4) - neigh_atoms.unsqueeze(3)
                dist_25 = torch.sqrt(torch.sum(diff_25 * diff_25, dim=-1) + 1e-6).reshape(B, L, K, 25)
                rbf = torch.exp(
                    -(((dist_25.unsqueeze(-1) - self.rbf_centers) / self.rbf_sigma) ** 2)
                ).reshape(B, L, K, 25 * self.num_rbf)

                # Relative sequence position encoding [-32..+32] -> 65 one-hot
                pos_i = torch.arange(L, device=backbone_coords.device).view(1, L, 1)
                rel_pos = torch.clamp(pos_i - E_idx, min=-32, max=32) + 32  # [B, L, K] in 0..64
                rel_oh = F.one_hot(rel_pos.long(), num_classes=65).float()

                edge_raw = torch.cat([rbf, rel_oh], dim=-1)
                h_E = self.W_e(self.norm_edges(self.edge_embedding(edge_raw))) * mask_bw.unsqueeze(-1)
                return h_E, E_idx, mask_bw

            def forward(
                self,
                backbone_coords: torch.Tensor,
                residue_valid_mask: torch.Tensor,
            ) -> torch.Tensor:
                B, L, _, _ = backbone_coords.shape
                mask_V = residue_valid_mask.float()
                h_E, E_idx, mask_bw = self._featurize_backbone_graph(backbone_coords, residue_valid_mask)
                h_V = torch.zeros((B, L, self.hidden_dim), dtype=h_E.dtype, device=h_E.device)
                for layer in self.encoder_layers:
                    h_V, h_E = layer(h_V, h_E, E_idx, mask_V, mask_bw)
                return h_V * mask_V.unsqueeze(-1)

